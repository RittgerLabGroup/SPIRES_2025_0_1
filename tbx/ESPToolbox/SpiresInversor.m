    % Function to optimize between modeled reflectance and observed reflectance, based
    % on lookup table structure by Jeff (spiresModelForModis = 0).
    function reflectanceDifference = hyperspectralLookup(obj, ...
      x, thisReflectance, thisBackgroundReflectance, thisSolarZenith)
      modisData = obj.region.espEnv.modisData;
      % x is the set of values snowFraction, shadeFraction, grainSize,
      % dustConcentration

      modelReflectance = zeros(length(thisReflectance), 1);
      % x is x(1) = fsca (in percent), x(2) = fshade (in percent), x(3) = radius,
      % x(4) = dust.
      % Dust are not in the same "units" between Ned's and Jeff's code.

      muI = cosd(thisSolarZenith);
      radius = x(3);
      LAPfraction = x(4) / 10^6;
        % NB: dust values are to be modified if we use Ned's lookup
        % table, because his code expresses dust in ppm., which should be x 1000000 to
        % get dimensionless fractions as expected by Jeff's code lookup table.

      % Below is a simplification of the code provided by Jeff of
      % SnowToday.UseInterpolation.SnowMultiSpectralLookupSpires(), which finds
      % values in a pre-generated
      % lookup table (by us with the code of Jeff).
      dustF = LAPfraction;
      sootF = 0;
      thatSize = [1, length(thisReflectance)];
      modelReflectance = obj.spiresGriddedInterpolant( ...
        obj.reflectanceNumerosInInterpolant.(modisData.inputProduct), ...
        repmat(muI, thatSize), repmat(sqrt(radius), thatSize), ...
        repmat(dustF, thatSize), repmat(sootF, thatSize))';
        % Spires Bair 2021, p. 7272: directional estimate of surface reflectance?
        % We assume it's direct reflectance and not diffuse reflectance here.
        %                                                                     @tocheck
        % The lookup table is the field Fdirty of the interpolant, which has been
        % copied in the field data obtained by
        % espEnv.getDataForObjectNameDataLabel().

      modelReflectance = (x(1) .* modelReflectance + ...
        (1 - x(1) - x(2)) .* thisBackgroundReflectance);
      reflectanceDifference = double(norm(thisReflectance - modelReflectance));
        % double type required by fmincon.
    end % function hyperspectralLookup().
    
    % Function to optimize between modeled reflectance and observed reflectance, based
    % on lookup table structure by Ned (spiresModelForModis = 1).
    % I split both methods because the call to obj.spiresGriddedInterpolant through
    % fmincon() doesn't work (the run expect a certain structure of the
    % griddedInterpolant, which is different between Ned and Jeff's version, and
    % is not accepted by Matlab even through a condition.
    function reflectanceDifference = hyperspectralLookupByNed(obj, ...
      x, thisReflectance, thisBackgroundReflectance, thisSolarZenith)
      modisData = obj.region.espEnv.modisData;
      % x is the set of values snowFraction, shadeFraction, grainSize,
      % dustConcentration

      modelReflectance = zeros(length(thisReflectance), 1);
      % x is x(1) = fsca (in percent), x(2) = fshade (in percent), x(3) = radius,
      % x(4) = dust.
      % Dust are not in the same "units" between Ned's and Jeff's code.
      for i=1:length(thisReflectance)
        %use radius,dust,solarZenith, and band # for look up
        modelReflectance(i) = ...
          obj.spiresGriddedInterpolant([x(3), x(4), thisSolarZenith, i]);
      end
      modelReflectance = (x(1) .* modelReflectance + ...
        (1 - x(1) - x(2)) .* thisBackgroundReflectance);
      reflectanceDifference = double(norm(thisReflectance - modelReflectance));
        % double type required by fmincon.
    end % function hyperspectralLookup().
