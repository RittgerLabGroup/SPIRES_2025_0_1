      % metaData.inputFileStatus: 0: absent or corrupted input file, data filled with
      % no data. 1: valid file.
      % metaData.statusOfInversion: 0: not achieved. 1: achieved.
      
      defaultMetadataFieldNames = fieldnames(defaultMetaData);
      metaDataFieldNames = fieldnames(metaData);
      for thisFieldNameId = 1:length(defaultMetadataFieldNames)
        thisFieldName = defaultMetadataFieldNames{thisFieldNameId};
        if ~ismember(thisFieldName, metaDataFieldNames)
          metaData.(thisFieldName) = defaultMetaData.(thisFieldName);
        end
      end
      save(outputFilePath, 'metaData', '-append');
      
      %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
      % Determine if we ingest a new file or not, taking into account a possible 
      % corrupted file.
      %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
      inputFileIsToIngest = 0; % 0: no ingest of inputProduct, 1: ingest.
      inputFileIsCorrupted = 0; % 0: not corrupted (or no input file), 1: corrupted.
      inputIsToSetToNoData = 0; % 0: no set to nodata, 1: set to nodata.
      calculationsAreToSetToNoData = 0; % 0: weight and inversion results no set to
        % nodata, 1: set to nodata.
      weightAreToBeCalculated = 0; % 0: no weight calculations, 1: weight calculations
        % to do.
      rawSnowPropertiesAreToBeInversed = 0; 
        % 0: no spires inversion, 1: inversions to do.
      correctedSnowIsToBeCalculated = 0; % 0: Corrected snow (raw_snow_fraction) not to
        % be calculated, 1: to be calculated.
      spatialGrainSizeDustAreToBeCalculated = 0; % 0: Spatial grain size and dust
        % (spatial_grain_size, spatial_dust_concentration) not tobe calculated, 1: to
        % be calculated.
      
      % Check whether file is not corrupted, if file is distinct from metadata recorded
      % input file and if ok, set to be ingested.
      %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
      % We try to get some data in the file.
      % NB: should be a distinct method in ESPEnv.                                 @todo
      if inputFileExists && ( ...
        ~(isequal(inputFileName, metaData.inputDiscardedFileName) && ...
          isequal(inputFileLastEditDate, metaData.inputDiscardedFileLastEditDate)) ... 
        && (~isequal(metaData.inputFileLastEditDate, inputFileLastEditDate) || ...
        optim.force == 99))
        %
        varName = 'reflectance_6_1628_1652';
          % band 6 for mod09ga, i3 for vnp09ga, both at 463 m.
        complementaryLabel = '';
        thisOptim = optim;
        thisOptim.countOfCellPerDimension = [ ...
          espEnv.modisData.sensorProperties.tiling.rowPixelCount, ...
          espEnv.modisData.sensorProperties.tiling.columnPixelCount];
          % We'll only get the first pixel.
        try
          [varData, ~] = espEnv.getDataForDateAndVarName(...
            objectName, inputDataLabel, thisDate, varName, ...
            complementaryLabel, optim = thisOptim, ...
            patternsToReplaceByJoker = patternsToReplaceByJoker);
          inputFileIsToIngest = 1;
          metaData.inputFileName = inputFileName;
          metaData.inputFileLastEditDate = inputFileLastEditDate;
        catch thisException
          metaData.inputFileNameDiscarded = inputFileName;
          inputFileIsCorrupted = 1;
        end % try.
      end % if inputFileExists.

      %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
      % Determine the other tasks to carry out as a function of optim.force.
      %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
      if metaData.statusOfIngest == 0 && inputFileIsToIngest == 0
        inputIsToSetToNoData = 1;
        calculationsAreToSetToNoData = 1;
      else
        switch optim.force
          case 0
            if inputFileIsToIngest == 1
              weightAreToBeCalculated = 1;
              rawSnowPropertiesAreToBeInversed = 1;
              correctedSnowIsToBeCalculated = 1;
              spatialGrainSizeDustAreToBeCalculated = 1;
            end
          case 1
            % if input filename and its
            % modification date (lastEditDate) are identic to metaData recorded in
            % output file, or if no input file, doesnt update the data directly
            % extracted from the
            % input (i.e. using espEnv.getAndSaveData(), but update the data
            % calculated.
            %
            if ~isequal(metaData.inputFileName, '') && ...
              ~(isequal(metaData.inputFileName, metaData.inputDiscardedFileName) && ...
                isequal( ...
                  inputFileLastEditDate, metaData.inputDiscardedFileLastEditDate))
              weightAreToBeCalculated = 1;
              rawSnowPropertiesAreToBeInversed = 1;
              correctedSnowIsToBeCalculated = 1;
              spatialGrainSizeDustAreToBeCalculated = 1;
            else
              % weight and rawSnow are already set to no data.
            end
          case 10
            % update only the mod09ga/vnp09ga source data, including
            % clouds but excluding weights. This mode is useful for saving reflectance
            % ready to be used
            % for the background reflectance calculations.
            %
          case 20
            % update only raw_snow_fraction_s from data in spires daily file.
            correctedSnowIsToBeCalculated = 1;
          case 99
            if ~isequal(metaData.inputFileName, '') && ...
              ~(isequal(metaData.inputFileName, metaData.inputDiscardedFileName) && ...
                isequal( ...
                  inputFileLastEditDate, metaData.inputDiscardedFileLastEditDate))
              weightAreToBeCalculated = 1;
              rawSnowPropertiesAreToBeInversed = 1;
              correctedSnowIsToBeCalculated = 1;
              spatialGrainSizeDustAreToBeCalculated = 1;
            end
        end
      end
      fprintf(['%s: Status: inputFileIsToIngest: %d, inputFileIsCorrupted: %d, ', ...
        'inputIsToSetToNoData: %d, calculationsAreToSetToNoData: %d, ', ...
        'rawSnowPropertiesAreToBeInversed: %d, weightAreToBeCalculated: %d, ', ...
        'correctedSnowIsToBeCalculated: %d, spatialGrainSizeDustAreToBeCalculated:', ...
        ' %d.\n'], ...
        thisFunctionCode, inputFileIsToIngest, inputFileIsCorrupted, ...
        inputIsToSetToNoData, calculationsAreToSetToNoData, ...
        rawSnowPropertiesAreToBeInversed, weightAreToBeCalculated, ...
        correctedSnowIsToBeCalculated, spatialGrainSizeDustAreToBeCalculated);
      status = struct(inputFileIsToIngest = inputFileIsToIngest, ...
        inputFileIsCorrupted = inputFileIsCorrupted, ...
        inputIsToSetToNoData = inputIsToSetToNoData, ...
        calculationsAreToSetToNoData = calculationsAreToSetToNoData, ...
        rawSnowPropertiesAreToBeInversed = rawSnowPropertiesAreToBeInversed, ...
        weightAreToBeCalculated = weightAreToBeCalculated, ...
        correctedSnowIsToBeCalculated = correctedSnowIsToBeCalculated, ...
        spatialGrainSizeDustAreToBeCalculated = spatialGrainSizeDustAreToBeCalculated);
          
      % NB: The updated metadata are only saved at the end of the call of the main
      % method SpiresInversor.getInputAndHyperSpectralInverse().
    end
